#!/usr/bin/env python3
"""Sample SWE-bench Verified instance IDs into configs/pilot_instances.txt when datasets is installed."""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--n", type=int, default=200)
    p.add_argument("--seed", type=int, default=20260922)
    p.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "configs" / "pilot_instances.txt",
    )
    args = p.parse_args()

    try:
        from datasets import load_dataset
    except ImportError as e:
        raise SystemExit(
            "Install datasets (`pip install datasets`) to sample real SWE-bench Verified IDs.\n"
            "Placeholder IDs in configs/pilot_instances.txt are for dry-runs only."
        ) from e

    ds = load_dataset("princeton-nlp/SWE-bench_Verified", split="test")
    ids = sorted({row["instance_id"] for row in ds})
    import random

    rng = random.Random(args.seed)
    rng.shuffle(ids)
    chosen = ids[: args.n]
    header = (
        f"# SWE-bench Verified pilot instances n={len(chosen)} seed={args.seed}\n"
        "# Generated by scripts/sample_pilot_instances.py\n"
    )
    args.out.write_text(header + "\n".join(chosen) + "\n")
    print(f"Wrote {len(chosen)} ids to {args.out}")


if __name__ == "__main__":
    main()
